import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdtempSync, mkdirSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { execFileSync } from "node:child_process";
import { build } from "esbuild";
import express from "express";
import pg from "pg";
import { chromium } from "playwright-core";
import { SoldgraphCache } from "../../server/pricing/soldgraph-cache";
import type { SoldgraphClient } from "../../server/pricing/soldgraph-client";

assert.equal(process.env.NODE_ENV, "development", "Run only against the development database");
const schema = `market_browser_${process.pid}_${Date.now()}`;
const admin = new pg.Pool({ connectionString: process.env.DATABASE_URL });
const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL, options: `-c search_path=${schema}` });
const temp = mkdtempSync(join(tmpdir(), "market-browser-"));
const output = resolve("generated-artifacts/market-price-browser");
mkdirSync(output, { recursive: true });
let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
let server: ReturnType<ReturnType<typeof express>["listen"]> | undefined;
let providerCalls = 0;
const failures: string[] = [];
try {
  await admin.query(`CREATE SCHEMA ${schema}`);
  // LIKE copies structure, not customer data or foreign keys. Replace copied
  // serial defaults so inserts cannot advance the application's sequences.
  for (const table of ["badges", "user_badges", "notifications", "pending_card_images", "xp_events"]) {
    await pool.query(`CREATE TABLE ${table} (LIKE public.${table} INCLUDING ALL);
      ALTER TABLE ${table} ALTER COLUMN id DROP DEFAULT;
      ALTER TABLE ${table} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
  }
  await pool.query(`CREATE TABLE users(id int PRIMARY KEY, plan text, is_admin boolean DEFAULT false);
    INSERT INTO users VALUES(1,'SIDE_KICK',false),(2,'SIDE_KICK',false);
    CREATE TABLE main_sets(id int PRIMARY KEY,name text);
    CREATE TABLE card_sets(id int PRIMARY KEY,main_set_id int,year int,name text);
    CREATE TABLE cards(id int PRIMARY KEY,set_id int,name text,card_number text,variation text,archived_at timestamptz);
    CREATE TABLE card_price_cache(id serial,card_id int,avg_price numeric,sales_count int,last_fetched timestamptz);
    INSERT INTO main_sets VALUES(1,'2026 Topps Chrome Marvel');
    INSERT INTO card_sets VALUES(1,1,2026,'Fanfare');
    INSERT INTO cards(id,set_id,name,card_number) VALUES(1,1,'Knull','FF-23'),(2,1,'Knull','FF-23');`);
  const cache = new SoldgraphCache(pool, {
    search: async () => {
      providerCalls++;
      return { data: [{ id: "fixture", title: "2026 Topps Chrome Marvel Knull FF-23 Fanfare",
        link: "https://www.ebay.com/itm/1", displayed_price: { amount: 60, currency: "USD" },
        displayed_price_range: null, best_offer_accepted: false, sold_date: new Date().toISOString().slice(0, 10), condition: "Used" }] };
    },
  } as unknown as SoldgraphClient);
  (globalThis as any).__marketTestPool = pool;
  await build({
    entryPoints: ["scripts/market-price-browser/services.ts"], outfile: join(temp, "services.mjs"),
    bundle: true, platform: "node", format: "esm", packages: "external",
    plugins: [{ name: "isolated-database", setup(b) {
      b.onResolve({ filter: /(?:^|\/)db$/ }, () => ({ path: "db", namespace: "test" }));
      // Feed delivery is unrelated to the in-app badge notification contract.
      b.onResolve({ filter: /services\/feedService$/ }, () => ({ path: "feed", namespace: "test" }));
      b.onLoad({ filter: /.*/, namespace: "test" }, ({ path }) => ({ contents: path === "db"
        ? `import {drizzle} from 'drizzle-orm/node-postgres'; export const pool=globalThis.__marketTestPool; export const db=drizzle(pool);`
        : "export async function emitBadgeEarned() {}", loader: "js", resolveDir: process.cwd() }));
    } }],
  });
  // External dependencies resolve from the project, even though output is temporary.
  const { symlinkSync } = await import("node:fs");
  symlinkSync(resolve("node_modules"), join(temp, "node_modules"), "dir");
  const services = await import(pathToFileURL(join(temp, "services.mjs")).href);
  const bundle = await build({
    entryPoints: ["scripts/market-price-browser/view.tsx"], bundle: true, write: false,
    format: "esm", jsx: "automatic", alias: { "@": "./client/src", "@shared": "./shared", "@assets": "./attached_assets" },
    loader: { ".png": "dataurl", ".webp": "dataurl", ".svg": "dataurl" },
    define: { "process.env.NODE_ENV": '"production"', "import.meta.env": "{}" },
    plugins: [{ name: "isolated-identity", setup(b) {
      b.onResolve({ filter: /(?:contexts\/AuthContext|lib\/firebase|\.\/firebase)$/ }, () => ({ path: "auth", namespace: "test" }));
      b.onResolve({ filter: /lib\/collectorAvatars$/ }, () => ({ path: "avatars", namespace: "test" }));
      b.onLoad({ filter: /.*/, namespace: "test" }, ({ path }) => ({ contents: path === "avatars"
        ? "export const avatarUrl=()=>null; export const COLLECTOR_AVATARS=[];"
        : `const user={uid:'isolated',getIdToken:async()=>sessionStorage.getItem('test-token')}; export const auth={currentUser:user}; export const useAuth=()=>({user});`, loader: "js" }));
    } }],
  });
  execFileSync("node_modules/.bin/tailwindcss", ["-i", "client/src/index.css", "-o", join(temp, "style.css")], { stdio: "pipe" });
  const sessions = new Map<string, number>();
  const app = express();
  app.use(express.json());
  app.use("/api", (req, res, next) => {
    const token = req.headers.authorization?.replace(/^Bearer /, "") ??
      req.headers.cookie?.match(/test_session=([^;]+)/)?.[1];
    const id = token && sessions.get(token);
    if (!id) return res.status(401).json({ message: "Authentication required" });
    res.locals.userId = id;
    next();
  });
  const handle = (fn: (req: any, res: any) => Promise<any>) => (req: any, res: any, next: any) => fn(req, res).catch(next);
  app.get("/api/test-account", (_req, res) => res.json({
    id: res.locals.userId, username: `isolated${res.locals.userId}`, plan: "SIDE_KICK",
    isAdmin: false, onboardingComplete: true,
  }));
  app.get("/api/card-pricing/:id", handle(async (req, res) => res.json(await cache.read(Number(req.params.id)))));
  app.post("/api/card-pricing/:id/refresh", handle(async (req, res) => {
    const price = await cache.refresh(Number(req.params.id), res.locals.userId);
    await services.awardValueScout(res.locals.userId, price);
    res.json(price);
  }));
  app.get("/api/notifications/unread-count", handle(async (_req, res) =>
    res.json({ count: await services.notificationService.getUnreadCount(res.locals.userId) })));
  app.get("/api/notifications", handle(async (_req, res) =>
    res.json(await services.notificationService.getUserNotifications(res.locals.userId))));
  app.put("/api/notifications/:id/read", handle(async (req, res) => {
    const owned = await services.notificationService.getUserNotifications(res.locals.userId);
    assert.ok(owned.some((n: any) => n.id === Number(req.params.id)));
    await services.notificationService.markAsRead(Number(req.params.id));
    res.json({ success: true });
  }));
  app.get("/api/user/xp-summary", handle(async (_req, res) => {
    const xp = await services.computeUserXp(res.locals.userId);
    res.json({ ...xp.progress, breakdown: xp, recentXpEvents: [] });
  }));
  app.get("/api/social/user-badges", handle(async (_req, res) => {
    const rows = await pool.query(`SELECT ub.id,ub.earned_at AS "earnedAt",row_to_json(b) AS badge
      FROM user_badges ub JOIN badges b ON b.id=ub.badge_id WHERE user_id=$1`, [res.locals.userId]);
    res.json(rows.rows.map(r => ({ ...r, badge: { ...r.badge, iconUrl: r.badge.icon_url } })));
  }));
  app.get("/api/badges", handle(async (_req, res) => res.json((await pool.query("SELECT * FROM badges")).rows)));
  app.get("/api/badges/unlock-stats", (_req, res) => res.json({}));
  app.get("/api/social/relationships", (_req, res) => res.json({ friends: [], following: [], followers: [] }));
  app.get("/api/social/message-threads", (_req, res) => res.json([]));
  app.get("/api/social/unread-count", (_req, res) => res.json({ count: 0 }));
  app.post("/api/analytics/event", (_req, res) => res.json({ success: true }));
  app.use("/api", (req, res) => { failures.push(`Unhandled ${req.method} ${req.url}`); res.sendStatus(404); });
  app.get("/qa.js", (_req, res) => res.type("js").send(bundle.outputFiles[0].text));
  app.get("/style.css", (_req, res) => res.type("css").send(readFileSync(join(temp, "style.css"))));
  app.use(express.static("client/public"));
  app.get("*", (_req, res) => res.send('<meta name="viewport" content="width=device-width,initial-scale=1"><link rel="stylesheet" href="/style.css"><div id="root"></div><script type="module" src="/qa.js"></script>'));
  app.use((error: Error, _req: any, res: any, _next: any) => { failures.push(error.message); res.status(500).json({ message: error.message }); });
  server = app.listen(0, "127.0.0.1");
  await new Promise<void>(r => server!.once("listening", r));
  const base = `http://127.0.0.1:${(server.address() as any).port}`;
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/repl/tools/bin/chromium", args: ["--no-sandbox"] });
  for (const [index, width] of [1280, 393].entries()) {
    const userId = index + 1, token = randomUUID();
    sessions.set(token, userId);
    await pool.query("DELETE FROM soldgraph_price_cache").catch(() => {});
    // Initialize pricing tables with a read, then start just below the lifetime cap.
    await cache.read(1);
    await pool.query("INSERT INTO market_refresh_usage(user_id,consumed) VALUES($1,19)", [userId]);
    const context = await browser.newContext({ viewport: { width, height: 900 } });
    assert.equal((await context.request.post(`${base}/api/card-pricing/1/refresh`)).status(), 401);
    await context.addCookies([{ name: "test_session", value: token, url: base, httpOnly: true }]);
    await context.addInitScript(t => sessionStorage.setItem("test-token", t), token);
    const page = await context.newPage();
    page.on("pageerror", e => failures.push(e.message));
    await page.route("**/*", route => new URL(route.request().url()).origin === base ? route.continue() : route.abort());
    await page.goto(base);
    await page.getByText("0 total XP", { exact: true }).filter({ visible: true }).waitFor();
    const refresh = async (id: number) => {
      const response = page.waitForResponse(r => r.url().endsWith(`/api/card-pricing/${id}/refresh`));
      await page.getByTestId(`card-${id}`).getByRole("button").click();
      const result = await response;
      const body = await result.json();
      assert.equal(result.status(), 200, JSON.stringify(body));
      return body;
    };
    const callsBefore = providerCalls;
    assert.equal((await refresh(1)).avgPrice, 60);
    assert.equal(providerCalls, callsBefore + 1);
    await page.getByTestId("card-1").getByText("$60.00", { exact: false }).waitFor();
    assert.equal((await pool.query("SELECT consumed FROM market_refresh_usage WHERE user_id=$1", [userId])).rows[0].consumed, 20);
    const gated = await refresh(2);
    assert.equal(gated.upgradeRequired, true);
    const dialog = page.getByRole("dialog");
    await dialog.getByText("Unlock unlimited Market Price refreshes with SUPER_HERO.", { exact: true }).waitFor();
    const box = await dialog.boundingBox();
    assert.ok(box && box.x >= 0 && box.x + box.width <= width + 1, "upgrade dialog fits viewport");
    await page.screenshot({ path: join(output, `${width}-upgrade.png`) });
    await dialog.getByRole("button", { name: "Not now — I'll upgrade later" }).click();
    await dialog.waitFor({ state: "hidden" });
    assert.equal((await refresh(1)).avgPrice, 60, "fresh cache remains usable at cap");
    assert.equal(await dialog.count(), 0);
    assert.equal(providerCalls, callsBefore + 1, "cache and cap do not call provider");
    // Concurrent legitimate cache refreshes exercise actual ON CONFLICT award logic.
    await Promise.all(Array.from({ length: 5 }, () => context.request.post(`${base}/api/card-pricing/1/refresh`)));
    assert.equal((await pool.query("SELECT count(*)::int n FROM user_badges WHERE user_id=$1", [userId])).rows[0].n, 1);
    assert.equal((await services.notificationService.getUserNotifications(userId)).length, 1);
    assert.equal((await services.computeUserXp(userId)).totalXp, 10);
    await page.reload();
    await page.getByText("10 total XP", { exact: true }).filter({ visible: true }).waitFor();
    await page.getByTestId("button-xp-details").click();
    await page.getByText("XP Breakdown", { exact: true }).waitFor();
    const badgeXpRow = page.getByText("Super Power XP", { exact: true }).locator("..");
    assert.match(await badgeXpRow.innerText(), /10 XP/);
    await page.screenshot({ path: join(output, `${width}-xp.png`) });
    await page.keyboard.press("Escape");
    await page.locator("header button").click();
    await page.getByText('You\'ve earned the "Value Scout" badge!', { exact: false }).waitFor();
    assert.equal(await page.getByText("New Achievement Unlocked!", { exact: true }).count(), 1);
    await page.screenshot({ path: join(output, `${width}-notification.png`) });
    const readReceipt = page.waitForResponse(r => r.url().endsWith("/read") && r.request().method() === "PUT");
    await page.getByText("New Achievement Unlocked!", { exact: true }).click();
    assert.equal((await readReceipt).status(), 200);
    await page.waitForURL("**/social?tab=badges");
    await page.getByText("Value Scout", { exact: true }).first().waitFor();
    await page.screenshot({ path: join(output, `${width}-badge.png`) });
    assert.equal(await services.notificationService.getUnreadCount(userId), 0);
    await page.reload();
    await page.getByText("Value Scout", { exact: true }).first().waitFor();
    assert.equal((await services.notificationService.getUserNotifications(userId)).length, 1);
    assert.equal((await services.computeUserXp(userId)).totalXp, 10);
    assert.deepEqual(failures, []);
    console.log(`${width}px PASS: authenticated refresh, cap modal, fresh cache, one badge/notification/+10 XP, read and reload persistence`);
    await context.close();
  }
} finally {
  await browser?.close();
  await new Promise<void>(r => server ? server.close(() => r()) : r());
  await pool.end();
  await admin.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
  await admin.end();
  delete (globalThis as any).__marketTestPool;
  rmSync(temp, { recursive: true, force: true });
}
